'use strict';
const fs = require('node:fs'), path = require('node:path'), assert = require('node:assert/strict');
const src = fs.readFileSync(path.join(__dirname, 'src-js/10-model-adapters.js'), 'utf8');
const start = src.indexOf('const newCallId');
const end = src.indexOf('\n}\n', src.indexOf('function extractTextToolCalls')) + 3;
const mod = { exports: {} };
new Function('module', src.slice(start, end) + '\nmodule.exports={extractTextToolCalls};')(mod);
const { extractTextToolCalls } = mod.exports;
const tools = [{ name: 'browser_run_js', parameters: { properties: { code: { type: 'string' } } } }, { name: 'x', parameters: { properties: { n: { type: 'integer' }, b: { type: 'boolean' } } } }];
let n = 0; const ok = l => { n++; console.log('PASS', l); };

let r = extractTextToolCalls('Testing.\n<tool_call>\n<function=browser_run_js>\n<parameter=code>\nreturn {a:1};\n</parameter>\n</function>\n</tool_call>', tools);
assert.equal(r.calls.length, 1); assert.equal(r.calls[0].name, 'browser_run_js'); assert.equal(r.calls[0].args.code, 'return {a:1};'); assert.equal(r.text, 'Testing.');
ok('XML text tool call becomes a real call and is removed from the text');
r = extractTextToolCalls('<function=x><parameter=n>5</parameter><parameter=b>true</parameter></function>', tools);
assert.deepEqual(r.calls[0].args, { n: 5, b: true }); ok('arguments follow the tool schema types');
r = extractTextToolCalls('<tool_call>{"name":"x","arguments":{"n":3}}</tool_call>', tools);
assert.deepEqual(r.calls[0].args, { n: 3 }); ok('Hermes JSON form is supported');
r = extractTextToolCalls('<function=unknown><parameter=a>1</parameter></function>', tools);
assert.equal(r.calls.length, 0); assert.match(r.text, /unknown/); ok('tools that were not offered are ignored');
r = extractTextToolCalls('plain answer', tools); assert.equal(r.text, 'plain answer'); assert.equal(r.calls.length, 0); ok('plain answers pass through');
r = extractTextToolCalls('Checking.\n[Called tool browser_run_js with {"code":"return {a:[1]}"}]', tools);
assert.equal(r.calls.length, 1); assert.equal(r.calls[0].args.code, 'return {a:[1]}'); assert.equal(r.text, 'Checking.');
r = extractTextToolCalls('[Called tool nope with {"a":1}]', tools); assert.equal(r.calls.length, 0);
ok('the bridge\'s "[Called tool X with {json}]" form is converted too');
assert.match(src, /if \(!toolCalls\.length && tools\.length\)/); ok('callOpenAI uses the fallback');
const app = fs.readFileSync(path.join(__dirname, 'js/app.js'), 'utf8');
assert.ok(app.includes('function extractTextToolCalls')); ok('js/app.js bundle contains the fix');
console.log(n + ' checks passed');
